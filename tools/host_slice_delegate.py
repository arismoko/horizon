#!/usr/bin/env python3
"""Slice scaffolding (host-crate-slice, not for merge): turns the game's generated host impls
(`game_host_modules.rs`, `impl <Area> for Game`) into `impl<E> <Area> for HostOf<E>` that
delegate to `E`'s own impl of the area trait, except for the methods listed in MOVED, whose
forwarder body is kept (access check, conversions) and calls `crate::bodies::<name>` instead of
the game's inherent method.

    python3 tools/host_slice_delegate.py <game_host_modules.rs> > crates/horizon-mod-answers/src/host_delegate.rs
"""
import re, sys

MOVED = {
    'entity_position', 'entity_block_position', 'entity_rotation', 'entity_kind',
    'entity_level', 'entity_uuid', 'entity_leash_to_knot',
}

src = open(sys.argv[1]).read().split('\n')
out = ['// @generated by tools/host_slice_delegate.py from the game\'s generated host impls; do not edit.',
       'use super::HostOf;', 'use super::Legacy;', 'use engine_access::Subsystems;', 'use mod_api::*;', 'use std::path::PathBuf;', 'use std::sync::Arc;', '']

def split_top(s):
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch in '<([': depth += 1
        elif ch in '>)]': depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip(): parts.append(cur)
    return [p.strip() for p in parts]

i = 0
while i < len(src):
    m = re.match(r"impl mod_api::prelude::(\w+) for Game<'_> \{", src[i])
    if not m:
        i += 1; continue
    trait = m.group(1)
    i += 1
    out.append(f"impl<E: Legacy + Subsystems> mod_api::prelude::{trait} for HostOf<'_, E> {{")
    while src[i] != '}':
        if src[i].startswith('    fn '):
            j = i
            sig = src[j]
            while not (sig.rstrip().endswith('{') and (j == i or src[j].startswith('    )'))):
                j += 1; sig += '\n' + src[j]
            # body: until the line '    }'
            k = j + 1
            while src[k] != '    }':
                k += 1
            body = src[j + 1:k]
            head = sig.rstrip()[:-1].rstrip()
            name = re.match(r'\s*fn (\w+)', head).group(1)
            open_p = head.index('(')
            depth, p = 0, open_p
            while True:
                if head[p] == '(': depth += 1
                elif head[p] == ')':
                    depth -= 1
                    if depth == 0: break
                p += 1
            params = split_top(head[open_p + 1:p])
            mutable = params[0].replace(' ', '') == '&mutself'
            recv = '&mut *self.0' if mutable else '&*self.0'
            names = [q.split(':')[0].strip() for q in params[1:]]
            if name in MOVED:
                text = '\n'.join(body)
                text, n = re.subn(r'Game::%s\(self, ' % name, f'crate::bodies::{name}({recv}, ', text)
                assert n == 1, (trait, name)
                out.append(head + ' {')
                out.append(text)
            else:
                out.append(head + ' {')
                args = ', '.join([recv] + names)
                out.append(f"        <E as mod_api::prelude::{trait}>::{name}({args})")
            out.append('    }')
            i = k + 1
        else:
            i += 1
    out.append('}')
    i += 1
print('\n'.join(out))
