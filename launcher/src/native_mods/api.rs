//! The launcher's generated executable for trait mods.
use super::{Bundle, MANIFEST};
use std::fs;
use std::path::Path;

pub(super) fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 100
        && id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
}

fn read(path: &Path) -> Result<toml::Table, String> {
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    text.parse().map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, value: &toml::Table) -> Result<(), String> {
    let text = toml::to_string(value).map_err(|e| format!("{}: {e}", path.display()))?;
    fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// horizon-mixins rejects [api] until its manifest supports this launcher field.
pub(super) fn strip(bundle: &Bundle) -> Result<(), String> {
    if bundle.api.is_some() {
        let path = bundle.dir.join(MANIFEST);
        let mut manifest = read(&path)?;
        manifest.remove("api");
        write(&path, &manifest)?;
    }
    Ok(())
}

pub(super) fn needs_mixins(mods: &[Bundle]) -> Result<bool, String> {
    for bundle in mods {
        let manifest = read(&bundle.dir.join(MANIFEST))?;
        // Let horizon-mixins diagnose fields that this fast path does not understand.
        if manifest.keys().any(|key| {
            ![
                "mod",
                "compatibility",
                "api",
                "injection",
                "state",
                "bridge",
                "module",
                "crate",
                "post_build",
            ]
            .contains(&key.as_str())
        }) {
            return Ok(true);
        }
        for (section, allowed) in [
            ("mod", &["id", "version", "priority"][..]),
            ("compatibility", &["horizon_revision"][..]),
        ] {
            if let Some(value) = manifest.get(section) {
                if !value
                    .as_table()
                    .is_some_and(|table| table.keys().all(|key| allowed.contains(&key.as_str())))
                {
                    return Ok(true);
                }
            }
        }
        let info = &manifest["mod"];
        if info
            .get("priority")
            .is_some_and(|v| v.as_integer().and_then(|v| i32::try_from(v).ok()).is_none())
            || manifest
                .get("compatibility")
                .and_then(|v| v.get("horizon_revision"))
                .is_some_and(|v| !v.is_str())
        {
            return Ok(true);
        }
        // Crates and post-build steps also require the mixin tool's staging.
        if [
            "injection",
            "state",
            "bridge",
            "module",
            "crate",
            "post_build",
        ]
        .iter()
        .any(|key| {
            manifest
                .get(*key)
                .is_some_and(|value| value.as_array().is_none_or(|a| !a.is_empty()))
        }) {
            return Ok(true);
        }
    }
    Ok(false)
}

fn path_dep(path: &str) -> toml::Value {
    toml::Value::Table(toml::Table::from_iter([("path".into(), path.into())]))
}

fn main_rs(count: usize) -> String {
    let entries = (0..count)
        .map(|i| format!("        mod_{i}::hooks(),\n"))
        .collect::<String>();
    format!(
        "//! Generated by the launcher.\n#![forbid(unsafe_code)]\n\n#[global_allocator]\nstatic ALLOCATOR: horizon_threads::Allocator = horizon_threads::Allocator;\n\nstatic MOD_API_LEVEL: [u8; 27] = horizon_mods::api_level::MARK;\n\nfn main() {{\n    std::hint::black_box(&MOD_API_LEVEL);\n    let mods: horizon_client::mod_api::Mods = vec![\n{entries}    ].into();\n    horizon_client::entry::main_with(mods);\n}}\n"
    )
}

/// Add API packages and the generated executable to the fresh staged workspace.
pub(super) fn stage(stage: &Path, mods: &[Bundle]) -> Result<bool, String> {
    let mods: Vec<_> = mods.iter().filter(|m| m.api.is_some()).collect();
    if mods.is_empty() {
        return Ok(false);
    }
    let mut deps = toml::Table::new();
    for name in ["horizon-client", "horizon-threads", "horizon-mods"] {
        deps.insert(name.into(), path_dep(&format!("../crates/{name}")));
    }
    let mut members = Vec::new();
    for (i, bundle) in mods.iter().enumerate() {
        let relative = format!("native-api/{}", bundle.id);
        let dest = stage.join(&relative);
        let source = bundle.dir.join(bundle.api.as_ref().expect("filtered"));
        super::sync(&source, &dest)?;
        let path = dest.join("Cargo.toml");
        let mut manifest = read(&path)?;
        let package = manifest
            .get("package")
            .and_then(|p| p.get("name"))
            .and_then(toml::Value::as_str)
            .ok_or_else(|| format!("{}: missing package name", path.display()))?
            .to_owned();
        let dependencies = manifest
            .get_mut("dependencies")
            .and_then(toml::Value::as_table_mut)
            .ok_or_else(|| format!("{}: missing horizon-client dependency", path.display()))?;
        let dependency = dependencies
            .iter_mut()
            .find(|(key, value)| {
                *key == "horizon-client"
                    || value.get("package").and_then(toml::Value::as_str) == Some("horizon-client")
            })
            .ok_or_else(|| format!("{}: missing horizon-client dependency", path.display()))?
            .1;
        match dependency {
            toml::Value::Table(t) => {
                t.insert("path".into(), "../../crates/horizon-client".into());
                t.remove("git");
                t.remove("version");
                t.remove("rev");
                t.remove("branch");
                t.remove("tag");
            }
            _ => *dependency = path_dep("../../crates/horizon-client"),
        }
        write(&path, &manifest)?;
        let mut dep = toml::Table::new();
        dep.insert("path".into(), format!("../{relative}").into());
        dep.insert("package".into(), package.into());
        deps.insert(format!("mod_{i}"), toml::Value::Table(dep));
        members.push(relative);
    }
    let game = stage.join("native-game");
    fs::create_dir_all(game.join("src")).map_err(|e| e.to_string())?;
    let mut manifest = toml::Table::new();
    manifest.insert(
        "package".into(),
        toml::Value::Table(toml::Table::from_iter([
            ("name".into(), "horizon-native-game".into()),
            ("version".into(), "0.1.0".into()),
            ("edition".into(), "2024".into()),
            ("publish".into(), false.into()),
        ])),
    );
    manifest.insert(
        "bin".into(),
        toml::Value::Array(vec![toml::Value::Table(toml::Table::from_iter([
            ("name".into(), "horizon-client".into()),
            ("path".into(), "src/main.rs".into()),
        ]))]),
    );
    manifest.insert("dependencies".into(), toml::Value::Table(deps));
    write(&game.join("Cargo.toml"), &manifest)?;
    fs::write(game.join("src/main.rs"), main_rs(mods.len())).map_err(|e| e.to_string())?;
    let root = stage.join("Cargo.toml");
    let mut workspace = read(&root)?;
    let list = workspace
        .get_mut("workspace")
        .and_then(|w| w.get_mut("members"))
        .and_then(toml::Value::as_array_mut)
        .ok_or("workspace has no members")?;
    members.push("native-game".into());
    list.extend(members.into_iter().map(toml::Value::String));
    write(&root, &workspace)?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};

    fn fixture(manifest: &str) -> std::path::PathBuf {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let dir = std::env::temp_dir().join(format!(
            "native-api-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir_all(dir.join("engine/src")).unwrap();
        fs::write(dir.join(MANIFEST), manifest).unwrap();
        fs::write(dir.join("engine/Cargo.toml"), "[package]\nname = 'example-mod'\nversion = '0.1.0'\nedition = '2024'\n[dependencies]\nhorizon-client = '0.1'\n").unwrap();
        fs::write(dir.join("engine/src/lib.rs"), "").unwrap();
        dir
    }

    #[test]
    fn validates_the_api_folder() {
        for (path, valid) in [
            ("engine", true),
            ("missing", false),
            ("../engine", false),
            ("/engine", false),
        ] {
            let dir = fixture(&format!(
                "[mod]\nid = 'example'\nversion = '1'\n[api]\npath = {path:?}\n"
            ));
            assert_eq!(super::super::bundle(&dir, None).is_ok(), valid, "{path}");
            fs::remove_dir_all(dir).unwrap();
        }
    }

    #[test]
    fn removes_only_the_api_table_for_mixins() {
        let dir = fixture(
            "[mod]\nid = 'example'\nversion = '1'\n[api]\npath = 'engine'\n[[injection]]\nid = 'test'\n",
        );
        let bundle = super::super::bundle(&dir, None).unwrap();
        assert!(needs_mixins(std::slice::from_ref(&bundle)).unwrap());
        strip(&bundle).unwrap();
        let value = read(&dir.join(MANIFEST)).unwrap();
        assert!(!value.contains_key("api"));
        assert!(value.contains_key("injection"));
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn generated_main_keeps_mod_order() {
        for count in 0..=2 {
            let text = main_rs(count);
            assert!(text.contains("entry::main_with(mods)"));
            assert_eq!(text.matches("::hooks()").count(), count);
            if count == 2 {
                assert!(
                    text.find("mod_0::hooks()").unwrap() < text.find("mod_1::hooks()").unwrap()
                );
            }
        }
    }

    #[test]
    fn stages_api_without_a_dependency_cycle() {
        let dir = fixture("[mod]\nid = 'example'\nversion = '1'\n[api]\npath = 'engine'\n");
        let bundle = super::super::bundle(&dir, None).unwrap();
        let stage_dir = dir.join("workspace");
        fs::create_dir_all(&stage_dir).unwrap();
        fs::write(stage_dir.join("Cargo.toml"), "[workspace]\nmembers = []\n").unwrap();
        assert!(stage(&stage_dir, &[bundle]).unwrap());
        let root = read(&stage_dir.join("Cargo.toml")).unwrap();
        let members = root["workspace"]["members"].as_array().unwrap();
        assert!(
            members
                .iter()
                .any(|v| v.as_str() == Some("native-api/example"))
        );
        assert!(members.iter().any(|v| v.as_str() == Some("native-game")));
        let engine = read(&stage_dir.join("native-api/example/Cargo.toml")).unwrap();
        assert_eq!(
            engine["dependencies"]["horizon-client"]["path"].as_str(),
            Some("../../crates/horizon-client")
        );
        let game = read(&stage_dir.join("native-game/Cargo.toml")).unwrap();
        assert_eq!(
            game["dependencies"]["mod_0"]["package"].as_str(),
            Some("example-mod")
        );
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn api_only_skips_mixins() {
        let dir = fixture("[mod]\nid = 'example'\nversion = '1'\n[api]\npath = 'engine'\n");
        let bundle = super::super::bundle(&dir, None).unwrap();
        assert!(!needs_mixins(&[bundle]).unwrap());
        fs::remove_dir_all(dir).unwrap();
    }
}
