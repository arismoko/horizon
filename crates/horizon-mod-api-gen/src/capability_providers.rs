//! The capability provider enums `mod_api` includes, derived from its capability keys.
use crate::index::{Found, Index};
use quote::ToTokens;
use std::path::Path;
use syn::Item;

/// A capability key's shape: what its providers are registered by, its handler trait as
/// written (`ResourceHandler<ItemResource>`), and an entity key's lookup context.
#[derive(Clone, PartialEq)]
pub(crate) struct KeyShape {
    pub(crate) by: &'static str,
    pub(crate) handler: String,
    pub(crate) context: String,
}

/// Every exported capability declaration, including keys sharing a handler shape.
fn key_declarations(index: &mut Index<'_>) -> Result<Vec<(String, KeyShape)>, String> {
    let api = index.module("mod_api", &[])?;
    let names: Vec<String> = index.modules[api]
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Use(item) if matches!(item.vis, syn::Visibility::Public(_)) => Some(&item.tree),
            _ => None,
        })
        .flat_map(use_names)
        .collect();
    let mut declarations = Vec::new();
    for name in names {
        let Ok(Found::Item(id)) = index.resolve(api, &name) else {
            continue;
        };
        let Item::Const(item) = index.item(id) else {
            continue;
        };
        let syn::Type::Path(path) = &*item.ty else {
            continue;
        };
        let Some(last) = path.path.segments.last() else {
            continue;
        };
        let by = match last.ident.to_string().as_str() {
            "CapabilityKey" => "Block",
            "ItemCapabilityKey" => "Item",
            "EntityCapabilityKey" => "Entity",
            _ => continue,
        };
        let syn::PathArguments::AngleBracketed(args) = &last.arguments else {
            continue;
        };
        let mut args = args.args.iter();
        let Some(syn::GenericArgument::Type(syn::Type::TraitObject(object))) = args.next() else {
            continue;
        };
        let context = match args.next() {
            Some(syn::GenericArgument::Type(ty)) => written(ty),
            _ => "()".to_string(),
        };
        let shape = KeyShape {
            by,
            handler: trait_name(object)?,
            context,
        };
        declarations.push((name, shape));
    }
    Ok(declarations)
}

/// Distinct provider shapes, in the order their keys are exported.
pub(crate) fn key_shapes(index: &mut Index<'_>) -> Result<Vec<KeyShape>, String> {
    let mut shapes = Vec::new();
    for (_, shape) in key_declarations(index)? {
        if !shapes.contains(&shape) {
            shapes.push(shape);
        }
    }
    Ok(shapes)
}

impl KeyShape {
    /// Its provider trait, as an owner (`BlockCapabilityProvider<dyn ResourceHandler<ItemResource>>`).
    pub(crate) fn provider(&self) -> String {
        match self.by {
            "Entity" => format!(
                "EntityCapabilityProvider<dyn {}, {}>",
                self.handler, self.context
            ),
            by => format!("{by}CapabilityProvider<dyn {}>", self.handler),
        }
    }
    /// Its case in the provider enum (`ResourceHandlerItemResource`).
    pub(crate) fn case(&self) -> String {
        let context = if self.by == "Entity" && self.context != "()" {
            self.context.as_str()
        } else {
            ""
        };
        heck::ToUpperCamelCase::to_upper_camel_case(format!("{} {context}", self.handler).as_str())
    }
}

/// The provider enums (`BlockProviderOf` and the item and entity forms): one case per key shape,
/// and `Own` for a mod's own handler type. `mod_api` includes them.
fn providers_code(shapes: &[KeyShape]) -> String {
    let mut code = String::from(
        "// @generated by horizon-mod-api-gen from mod_api's capability keys; do not edit.\n",
    );
    for (by, ctx) in [("Block", ""), ("Item", ""), ("Entity", ", C")] {
        let of = |shape: &KeyShape| format!("Arc<dyn {}>", shape.provider());
        let mine: Vec<&KeyShape> = shapes.iter().filter(|s| s.by == by).collect();
        let cases: String = mine
            .iter()
            .map(|s| format!("{}({}),\n", s.case(), of(s)))
            .collect();
        let tries: String = mine
            .iter()
            .map(|s| {
                format!(
                    "let any = match any.downcast::<{}>() {{ Ok(p) => return Self::{}(*p), Err(any) => any }};\n",
                    of(s),
                    s.case()
                )
            })
            .collect();
        let names: String = mine
            .iter()
            .map(|s| {
                format!(
                    "Self::{}(_) => Arc::from(std::any::type_name::<dyn {}>()),\n",
                    s.case(),
                    s.handler
                )
            })
            .collect();
        let gets: String = mine
            .iter()
            .map(|s| format!("Self::{}(p) => (p as &dyn Any).downcast_ref(),\n", s.case()))
            .collect();
        let (params, provider) = match by {
            "Entity" => (
                "<T: ?Sized + 'static, C: 'static>",
                "EntityCapabilityProvider<T, C>",
            ),
            _ => ("<T: ?Sized + 'static>", ""),
        };
        let provider = if provider.is_empty() {
            format!("{by}CapabilityProvider<T>")
        } else {
            provider.to_string()
        };
        let _ = ctx;
        code.push_str(&format!(
            "/// A {by} capability's provider, by its handler type.\n#[doc(hidden)]\n#[derive(Clone, horizon_mod_api_macros::Wire)]\npub enum {by}ProviderOf {{\n{cases}/// A handler type of a mod's own.\nOwn(OwnProvider),\n}}\nimpl {by}ProviderOf {{\n/// `provider`, by its handler type.\npub(crate) fn of{params}(provider: Arc<dyn {provider}>) -> Self {{\nlet any: Box<dyn Any + Send + Sync> = Box::new(provider);\n{tries}Self::Own(OwnProvider {{ provider: Arc::from(any), handler: Arc::from(std::any::type_name::<T>()) }})\n}}\n/// Its handler type's name.\npub(crate) fn handler(&self) -> Arc<str> {{\nmatch self {{\n{names}Self::Own(own) => own.handler.clone(),\n}}\n}}\n/// The provider, if it answers with handler type `T`.\npub(crate) fn get{params}(&self) -> Option<&Arc<dyn {provider}>> {{\nmatch self {{\n{gets}Self::Own(own) if own.provider.is::<crate::wire::Unsupported>() => None,\nSelf::Own(own) => (*own.provider).downcast_ref(),\n}}\n}}\n}}\n"
        ));
    }
    code
}

/// Every name a `use` tree brings in.
pub(crate) fn use_names(tree: &syn::UseTree) -> Vec<String> {
    match tree {
        syn::UseTree::Path(path) => use_names(&path.tree),
        syn::UseTree::Name(name) => vec![name.ident.to_string()],
        syn::UseTree::Rename(rename) => vec![rename.rename.to_string()],
        syn::UseTree::Group(group) => group.items.iter().flat_map(use_names).collect(),
        syn::UseTree::Glob(_) => Vec::new(),
    }
}

/// A trait object's trait as the generator names it: its last path segment, with its type
/// arguments as written (`ResourceHandler<ItemResource>`).
fn trait_name(object: &syn::TypeTraitObject) -> Result<String, String> {
    object
        .bounds
        .iter()
        .find_map(|bound| match bound {
            syn::TypeParamBound::Trait(bound) => bound.path.segments.last().map(|s| {
                let args = match &s.arguments {
                    syn::PathArguments::AngleBracketed(args) => format!(
                        "<{}>",
                        args.args.iter().map(written).collect::<Vec<_>>().join(", ")
                    ),
                    _ => String::new(),
                };
                format!("{}{args}", s.ident)
            }),
            _ => None,
        })
        .ok_or_else(|| format!("dyn {}", object.to_token_stream()))
}

/// Tokens as written, without the spaces `quote` puts around punctuation
/// (`Option<Direction>`, `dyn ResourceHandler<ItemResource>`).
fn written(tokens: &impl ToTokens) -> String {
    tokens
        .to_token_stream()
        .to_string()
        .replace(" < ", "<")
        .replace("< ", "<")
        .replace(" <", "<")
        .replace(" >", ">")
        .replace(" ,", ",")
        .replace("( )", "()")
}

/// The provider enums, and the source files read to derive them.
pub fn generate(
    root: &Path,
    included: &[(&str, &str)],
) -> Result<(String, Vec<std::path::PathBuf>), String> {
    let index = &mut Index::new(root, included);
    let declarations = key_declarations(index)?;
    let mut shapes = Vec::new();
    for (_, shape) in &declarations {
        if !shapes.contains(shape) {
            shapes.push(shape.clone());
        }
    }
    let mut providers = providers_code(&shapes);
    let block_keys = declarations
        .iter()
        .filter(|(_, shape)| shape.by == "Block")
        .map(|(name, shape)| {
            format!(
                "(crate::{name}.name, std::any::type_name::<dyn {}>()),",
                shape.handler
            )
        })
        .collect::<String>();
    providers.push_str(&format!(
        "pub(crate) fn builtin_block_capabilities() -> Vec<(&'static str, &'static str)> {{ vec![{block_keys}] }}\n"
    ));
    Ok((providers, index.read.take()))
}
