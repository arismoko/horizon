//! Side operations for mod-API host adapters (`AttachmentHost`, `GameHost::residence`).
use crate::game::transactions::decision::Residence;
use mod_api::AttachmentAccess;

pub trait ModapiSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    fn side_attachment_map(
        &mut self,
        holder: mod_api::Holder,
        access: AttachmentAccess,
    ) -> std::result::Result<&mut mod_api::Attachments, mod_api::AttachmentError> {
        <Self::State as SideOps>::side_attachment_map(self, holder, access)
    }

    fn side_entity_residence(&self, holder: mod_api::EntityRef) -> Residence {
        <Self::State as SideOps>::side_entity_residence(self, holder)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> ModapiSideGameExt<'__sg> for T {}

// Generated by Shape G codemod from side_* role dispatchers.
pub trait SideOps: Sized {
    type Game<'g>;

    fn side_attachment_map<'__side_g>(
        game: &'__side_g mut Self::Game<'_>,
        holder: mod_api::Holder,
        access: AttachmentAccess,
    ) -> std::result::Result<&'__side_g mut mod_api::Attachments, mod_api::AttachmentError>;
    fn side_entity_residence(game: &Self::Game<'_>, holder: mod_api::EntityRef) -> Residence;
}
