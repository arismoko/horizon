//! Role dispatchers owned by lane `blocks` (`side_ops/blocks.rs`).
use crate::game::{piston_push, stations_common};
use sunrise_core::{geometry::Vec3, nbt::Tag};
use sunrise_game_data::Result;
use sunrise_level::containers::BlockEntity;
use sunrise_world::entity_move::MoverType;
use sunrise_world::moving_colliders::Prepared;

pub trait BlocksSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    fn side_encode_live_block_entity(
        &self,
        key: (i32, i32, i32),
        entity: &BlockEntity,
        block: &str,
    ) -> Tag {
        <Self::State as SideOps>::side_encode_live_block_entity(self, key, entity, block)
    }

    fn side_station_changed(&mut self) {
        <Self::State as SideOps>::side_station_changed(self)
    }

    fn side_combiner_take_effects(
        &mut self,
        kind: stations_common::Kind,
        pos: [i32; 3],
        level_change: i32,
    ) -> bool {
        <Self::State as SideOps>::side_combiner_take_effects(self, kind, pos, level_change)
    }

    fn side_move_local_player(
        &mut self,
        mover: MoverType,
        movement: Vec3,
        auto_jump: bool,
    ) -> Result<Option<Vec3>> {
        <Self::State as SideOps>::side_move_local_player(self, mover, movement, auto_jump)
    }

    fn side_push_piston_entities(&mut self, pushes: Vec<piston_push::Push>) {
        <Self::State as SideOps>::side_push_piston_entities(self, pushes)
    }

    fn side_carry_pass(&mut self, start: &Prepared) {
        <Self::State as SideOps>::side_carry_pass(self, start)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> BlocksSideGameExt<'__sg> for T {}

// Generated by Shape G codemod from side_* role dispatchers.
pub trait SideOps: Sized {
    type Game<'g>;

    fn side_encode_live_block_entity(
        game: &Self::Game<'_>,
        key: (i32, i32, i32),
        entity: &BlockEntity,
        block: &str,
    ) -> Tag;
    fn side_station_changed(game: &mut Self::Game<'_>);
    fn side_combiner_take_effects(
        game: &mut Self::Game<'_>,
        kind: stations_common::Kind,
        pos: [i32; 3],
        level_change: i32,
    ) -> bool;
    fn side_move_local_player(
        game: &mut Self::Game<'_>,
        mover: MoverType,
        movement: Vec3,
        auto_jump: bool,
    ) -> Result<Option<Vec3>>;
    fn side_push_piston_entities(game: &mut Self::Game<'_>, pushes: Vec<piston_push::Push>);
    fn side_carry_pass(game: &mut Self::Game<'_>, start: &Prepared);
}
