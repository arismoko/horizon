//! Role-dispatched world/level/tick/transaction side operations (rewritten to `SideOps` traits at switch).
use crate::game::GameLevel;
use crate::game::{Dim, commands_common::Target};
use sunrise_core::position::BlockPos;
use sunrise_game_data::Result;
use sunrise_items::items::ItemStack;
use sunrise_level::{
    chunk_streamer::ChunkState, environment::Environment, fast_hash::FxHashMap,
    shulker_box::Shulker, world::World,
};
use sunrise_sim::crafting::Recipes;
use sunrise_sim::{
    join_seq::{JoinSeq, residency::table::EntityLookup},
    mobs::Mob,
};
use sunrise_world::dimension_type::DimensionFacts;
use sunrise_world::{
    level::{Behaviours, Ticks},
    registry::BlockStateId,
};

pub trait WorldSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    #[inline(always)]
    fn side_remote_named_clock_time(&self, name: &str) -> Option<i64> {
        <Self::State as SideOps>::side_remote_named_clock_time(self.side_state(), name)
    }

    #[inline(always)]
    fn side_parked_block_ticks(&self, dimension: &str) -> Option<&Ticks> {
        <Self::State as SideOps>::side_parked_block_ticks(self, dimension)
    }

    #[inline(always)]
    fn side_server_resident_entity(&self, id: u32) -> EntityLookup<Target> {
        <Self::State as SideOps>::side_server_resident_entity(self, id)
    }

    #[inline(always)]
    fn side_with_level_access<R>(
        &mut self,
        placement_preview: bool,
        f: impl FnOnce(&Behaviours, &mut GameLevel<'_>, &mut Ticks) -> R,
    ) -> R {
        <Self::State as SideOps>::side_with_level_access(self, placement_preview, f)
    }

    #[inline(always)]
    fn side_after_with_level(&mut self) {
        <Self::State as SideOps>::side_after_with_level(self)
    }

    #[inline(always)]
    fn side_set_block_live(
        &mut self,
        pos: [i32; 3],
        state: BlockStateId,
        flags: i32,
        create_entity: bool,
    ) -> bool {
        <Self::State as SideOps>::side_set_block_live(self, pos, state, flags, create_entity)
    }

    #[inline(always)]
    fn side_update_chunk_tickets(&mut self) {
        <Self::State as SideOps>::side_update_chunk_tickets(self)
    }

    #[inline(always)]
    fn side_section_mesh_pending_in(&self, section: (i32, i32, i32)) -> bool {
        <Self::State as SideOps>::side_section_mesh_pending_in(self, section)
    }

    #[inline(always)]
    fn side_landing_change_cancelled(
        &mut self,
        player: Option<u128>,
        position: BlockPos,
        from: BlockStateId,
        to: BlockStateId,
    ) -> bool {
        <Self::State as SideOps>::side_landing_change_cancelled(self, player, position, from, to)
    }

    #[inline(always)]
    fn side_tick(&mut self) -> Result<()> {
        <Self::State as SideOps>::side_tick(self)
    }

    #[inline(always)]
    fn side_drop_stack_from_eyes(
        &mut self,
        stack: ItemStack,
        thrown_from_hand: bool,
    ) -> Option<u32> {
        <Self::State as SideOps>::side_drop_stack_from_eyes(self, stack, thrown_from_hand)
    }

    #[inline(always)]
    fn side_give_experience_points(&mut self, points: i32) {
        <Self::State as SideOps>::side_give_experience_points(self, points)
    }

    #[inline(always)]
    fn side_journal_entity(&mut self, id: u32) {
        <Self::State as SideOps>::side_journal_entity(self, id)
    }

    #[inline(always)]
    fn side_active_level_ref(&self, epoch: mod_api::WorldEpoch) -> Option<mod_api::LevelRef> {
        <Self::State as SideOps>::side_active_level_ref(self, epoch)
    }

    #[inline(always)]
    fn side_recipes(&self) -> &Recipes {
        <Self::State as SideOps>::side_recipes(self)
    }

    #[inline(always)]
    #[allow(dead_code)]
    fn side_reset_entity_residency(&mut self) {
        <Self::State as SideOps>::side_reset_entity_residency(self)
    }

    #[inline(always)]
    fn side_game_side_meta(&self) -> (Option<u128>, Option<mod_api::LevelRef>, bool) {
        <Self::State as SideOps>::side_game_side_meta(self)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> WorldSideGameExt<'__sg> for T {}

