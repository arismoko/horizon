//! Role-dispatched LAN side operations (rewritten to `SideOps` traits at switch).

use sunrise_sim::lan::guest::Guest;

pub trait LanSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    /// Whether a server player rides `vehicle` (`Entity.isPassenger`: a
    /// passenger does not use a portal on its own, the vehicle carries it
    /// across, `Entity.teleportCrossDimension`).
    fn guest_rides(&self, vehicle: u32) -> bool {
        <Self::State as SideOps>::side_guest_rides(self.side_state(), vehicle)
    }

    #[inline(always)]
    fn side_object_target(&self, id: i32) -> Option<([f64; 3], [f64; 3], [f64; 3])> {
        <Self::State as SideOps>::side_object_target(self, id)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> LanSideGameExt<'__sg> for T {}

// Generated by Shape G codemod from side_* role dispatchers.
pub trait SideOps: Sized {
    type Game<'g>;

    fn side_guest_rides(&self, vehicle: u32) -> bool;
    fn side_command_players(&self) -> impl Iterator<Item = &Guest>;

    fn side_object_target(game: &Self::Game<'_>, id: i32)
    -> Option<([f64; 3], [f64; 3], [f64; 3])>;
}
