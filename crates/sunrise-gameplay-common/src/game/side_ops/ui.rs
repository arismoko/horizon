//! Role-dispatched UI, chat, block-entity NBT, item-splash, and level-bound side operations.

use sunrise_core::nbt::Tag;
use sunrise_sim::entities::ItemSplash;

pub trait UiSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    #[inline(always)]
    fn side_block_entity_nbt(&self, pos: [i32; 3]) -> Option<Tag> {
        <Self::State as SideOps>::side_block_entity_nbt(self, pos)
    }

    #[inline(always)]
    fn side_send_chat_command(&mut self, command: &str) {
        <Self::State as SideOps>::side_send_chat_command(self, command)
    }

    #[inline(always)]
    fn side_apply_item_splash(&mut self, splash: ItemSplash) {
        <Self::State as SideOps>::side_apply_item_splash(self, splash)
    }

    #[inline(always)]
    fn side_level_min_y(&self) -> i32 {
        <Self::State as SideOps>::side_level_min_y(self)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> UiSideGameExt<'__sg> for T {}

// Generated by Shape G codemod from side_* role dispatchers.
pub trait SideOps: Sized {
    type Game<'g>;

    fn side_block_entity_nbt(game: &Self::Game<'_>, pos: [i32; 3]) -> Option<Tag>;
    fn side_send_chat_command(game: &mut Self::Game<'_>, command: &str);
    fn side_apply_item_splash(game: &mut Self::Game<'_>, splash: ItemSplash);
    fn side_level_min_y(game: &Self::Game<'_>) -> i32;
}
