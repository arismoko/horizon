//! Role-dispatched presentation, registry, camera, memory, and test-instance side operations.
use crate::game::memory_common::{MemoryInputs, MemoryReport};
use sunrise_world::{collision_context::EntityContextKind, worldgen::structure::Rotation};
use {sunrise_sim::first_person_sim::Hand, sunrise_sim::first_person_sim::SwingAnimation};

pub trait PresentationSideGameExt<'__sg>: crate::game::SideGame<'__sg> {
    /// `LivingEntity.swing` with `getModifiedSwingDuration` after the item's `on_entity_swing` Part.
    fn swing_hand(&mut self, hand: Hand, animation: SwingAnimation) {
        self.try_swing_hand(hand, animation);
    }

    /// `swing(hand)` for the hand that acts, with the default animation. None while a mod's
    /// `PlayerRef::attack` runs `Player.attack`, which has no swing: the swing is its packet's.
    fn swing_arm(&mut self) {
        if self.side_fake_action_unswung() {
            return;
        }
        self.swing_hand(self.hand, SwingAnimation::DEFAULT);
    }

    #[inline(always)]
    fn side_fake_action_unswung(&self) -> bool {
        <Self::State as SideOps>::side_fake_action_unswung(self)
    }

    #[inline(always)]
    fn try_swing_hand(&mut self, hand: Hand, animation: SwingAnimation) -> bool {
        self.side_swing_hand(hand, animation)
    }

    #[inline(always)]
    fn side_swing_hand(&mut self, hand: Hand, animation: SwingAnimation) -> bool {
        <Self::State as SideOps>::side_swing_hand(self, hand, animation)
    }

    #[inline(always)]
    fn side_sound_event_names(&self) -> Vec<String> {
        <Self::State as SideOps>::side_sound_event_names(self)
    }

    #[inline(always)]
    fn side_sync_pack_tag_ids(&mut self) {
        <Self::State as SideOps>::side_sync_pack_tag_ids(self)
    }

    #[inline(always)]
    fn side_sync_hub_clocks(&mut self) {
        <Self::State as SideOps>::side_sync_hub_clocks(self)
    }

    #[inline(always)]
    fn side_has_singleplayer_server(&self) -> bool {
        <Self::State as SideOps>::side_has_singleplayer_server(self)
    }

    #[inline(always)]
    fn side_is_published(&self) -> bool {
        <Self::State as SideOps>::side_is_published(self)
    }

    #[inline(always)]
    fn side_clear_lod(&mut self) {
        <Self::State as SideOps>::side_clear_lod(self)
    }

    #[inline(always)]
    #[allow(dead_code)]
    fn side_clear_render_caches(&mut self) {
        <Self::State as SideOps>::side_clear_render_caches(self)
    }

    #[allow(dead_code)]
    #[inline(always)]
    fn side_expire_cracks(&mut self) {
        <Self::State as SideOps>::side_expire_cracks(self)
    }

    #[inline(always)]
    fn side_update_spawner_display(&mut self, key: (i32, i32, i32)) -> bool {
        <Self::State as SideOps>::side_update_spawner_display(self, key)
    }

    #[allow(dead_code)]
    #[inline(always)]
    fn side_memory_inputs(&self) -> MemoryInputs {
        <Self::State as SideOps>::side_memory_inputs(self)
    }

    #[inline(always)]
    fn side_memory_report(&self) -> MemoryReport {
        <Self::State as SideOps>::side_memory_report(self)
    }

    #[inline(always)]
    fn side_test_holder_padding(&self, pos: (i32, i32, i32)) -> i32 {
        <Self::State as SideOps>::side_test_holder_padding(self, pos)
    }

    #[inline(always)]
    fn side_test_rotation(&self, pos: (i32, i32, i32)) -> Rotation {
        <Self::State as SideOps>::side_test_rotation(self, pos)
    }

    #[inline(always)]
    fn side_pick_camera_id(&self) -> Option<u32> {
        <Self::State as SideOps>::side_pick_camera_id(self)
    }

    #[inline(always)]
    fn side_live_remote_camera_id(&self) -> Option<u32> {
        <Self::State as SideOps>::side_live_remote_camera_id(self)
    }

    #[inline(always)]
    fn side_is_pick_camera(&self, id: u32) -> bool {
        <Self::State as SideOps>::side_is_pick_camera(self, id)
    }

    #[inline(always)]
    fn side_outline_camera_kind(&self) -> EntityContextKind {
        <Self::State as SideOps>::side_outline_camera_kind(self)
    }

    #[inline(always)]
    fn side_close_container(&mut self) {
        <Self::State as SideOps>::side_close_container(self)
    }
}
impl<'__sg, T: crate::game::SideGame<'__sg>> PresentationSideGameExt<'__sg> for T {}

// Generated by Shape G codemod from side_* role dispatchers.
pub trait SideOps: Sized {
    type Game<'g>;

    fn side_swing_hand(game: &mut Self::Game<'_>, hand: Hand, animation: SwingAnimation) -> bool;
    fn side_fake_action_unswung(game: &Self::Game<'_>) -> bool;
    fn side_sound_event_names(game: &Self::Game<'_>) -> Vec<String>;
    fn side_sync_pack_tag_ids(game: &mut Self::Game<'_>);
    fn side_sync_hub_clocks(game: &mut Self::Game<'_>);
    fn side_has_singleplayer_server(game: &Self::Game<'_>) -> bool;
    fn side_is_published(game: &Self::Game<'_>) -> bool;
    fn side_clear_lod(game: &mut Self::Game<'_>);
    fn side_clear_render_caches(game: &mut Self::Game<'_>);
    fn side_expire_cracks(game: &mut Self::Game<'_>);
    fn side_update_spawner_display(game: &mut Self::Game<'_>, key: (i32, i32, i32)) -> bool;
    fn side_memory_inputs(game: &Self::Game<'_>) -> MemoryInputs;
    fn side_memory_report(game: &Self::Game<'_>) -> MemoryReport;
    fn side_test_holder_padding(game: &Self::Game<'_>, pos: (i32, i32, i32)) -> i32;
    fn side_test_rotation(game: &Self::Game<'_>, pos: (i32, i32, i32)) -> Rotation;
    fn side_pick_camera_id(game: &Self::Game<'_>) -> Option<u32>;
    fn side_live_remote_camera_id(game: &Self::Game<'_>) -> Option<u32>;
    fn side_is_pick_camera(game: &Self::Game<'_>, id: u32) -> bool;
    fn side_outline_camera_kind(game: &Self::Game<'_>) -> EntityContextKind;
    fn side_close_container(game: &mut Self::Game<'_>);
}
