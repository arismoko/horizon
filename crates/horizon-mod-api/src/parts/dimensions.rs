use super::*;
/// The dimensions registered at startup, for the executable to hand to the engine.
pub(crate) fn installed_dimension_list() -> &'static [crate::dimension::DimensionInfo] {
    installed().map_or(&[], |installed| installed.dimensions.as_slice())
}

/// The levels every world has, which no mod's can be.
#[cfg(not(target_arch = "wasm32"))]
const VANILLA_DIMENSIONS: [&str; 3] = [
    "minecraft:overworld",
    "minecraft:the_nether",
    "minecraft:the_end",
];

impl PartRegistrar {
    /// Refuses a dimension whose generator no one provides. After every mod has
    /// registered, as a generator may come from a later mod's registration.
    pub(crate) fn refuse_unknown_dimension_generators(&mut self) {
        for dimension in &self.dimensions {
            let generator = &dimension.settings.generator;
            if generator != crate::dimension::NOISE_GENERATOR {
                self.refused.push(format!(
                    "{} registered dimension {} with the unknown generator {generator:?}",
                    dimension.mod_id, dimension.id
                ));
            }
        }
    }
}

impl dyn Registrar + '_ {
    /// Register dimension `name` (`pocket` or `mymod:pocket`) once at startup:
    /// every world then has the level `mymod:pocket`, shaped and generated by
    /// `settings`, as if a data pack below all the others gave it. A data pack
    /// can replace its level stem or dimension type. The id is in the calling
    /// mod's namespace; another mod's namespace, an empty name, a vanilla
    /// level, an id registered twice, a build height the dimension type codec
    /// refuses and an unknown generator refuse the mods at startup, naming
    /// the mod.
    #[cfg(not(target_arch = "wasm32"))]
    pub fn register_dimension(&mut self, name: &str, settings: crate::DimensionSettings) {
        self.add_dimension(name, settings);
    }
}

/// Registrar operations for dimensions.
pub trait DimensionsRegistrar {
    /// Register dimension `name` with `settings`; mods reach it through
    /// `register_dimension`.
    ///
    /// Not on wasm: dimension settings and their registration are a native
    /// mod's for now, an open question for #1042.
    /// The gate keeps a wasm mod's call a compile error, not a runtime one.
    // hidden: its types could cross, so the generator refuses this doc alone; hiding keeps it off
    // the wasm world
    #[doc(hidden)]
    #[cfg(not(target_arch = "wasm32"))]
    fn add_dimension(&mut self, name: &str, settings: crate::DimensionSettings);
}

impl DimensionsRegistrar for PartRegistrar {
    #[cfg(not(target_arch = "wasm32"))]
    fn add_dimension(&mut self, name: &str, settings: crate::DimensionSettings) {
        let (namespace, path) = name.split_once(':').unwrap_or((self.mod_id, name));
        let id = format!("{}:{}", self.mod_id, path);
        let refusal = if namespace != self.mod_id {
            Some(format!(
                "{} registered dimension {name:?} in the namespace {namespace:?}, which is not its own",
                self.mod_id
            ))
        } else if path.is_empty() {
            Some(format!(
                "{} registered a dimension with no name",
                self.mod_id
            ))
        } else if VANILLA_DIMENSIONS.contains(&id.as_str()) {
            Some(format!(
                "{} registered dimension {id}, which is a vanilla level",
                self.mod_id
            ))
        } else if self.dimensions.iter().any(|d| *d.id == *id) {
            Some(format!("{} registered dimension {id} twice", self.mod_id))
        } else if !settings.valid_shape() {
            Some(format!(
                "{} registered dimension {id} with a build height the game refuses: min_y {}, \
                 height {}, logical_height {}",
                self.mod_id, settings.min_y, settings.height, settings.logical_height
            ))
        } else {
            None
        };
        if let Some(refusal) = refusal {
            self.refused.push(refusal);
            return;
        }
        self.dimensions.push(crate::dimension::DimensionInfo {
            mod_id: self.mod_id,
            id: id.into(),
            settings,
        });
    }
}

/// Fixtures that tests of other crates use to install Parts.
#[cfg(any(test, feature = "testing"))]
pub mod tests {
    #[cfg(test)]
    use super::*;
    #[cfg(test)]
    use crate::*;

    /// Each dimension a mod may not register: every one is refused at
    /// startup, naming the mod.
    #[test]
    fn invalid_dimensions_refuse_registration() {
        use mod_api::DimensionSettings;
        struct Invalid;
        #[mod_api::__subscriptions]
        impl Hooks for Invalid {
            fn register(&self, r: &mut dyn Registrar, _: &mod_api::RegistrationContext) {
                r.register_dimension("pocket", DimensionSettings::default());
                r.register_dimension("pocket", DimensionSettings::default());
                r.register_dimension("other:pocket", DimensionSettings::default());
                r.register_dimension("", DimensionSettings::default());
                r.register_dimension(
                    "uneven",
                    DimensionSettings {
                        height: 40,
                        logical_height: 40,
                        ..Default::default()
                    },
                );
                r.register_dimension(
                    "low_ceiling",
                    DimensionSettings {
                        height: 64,
                        ..Default::default()
                    },
                );
                r.register_dimension(
                    "too_tall",
                    DimensionSettings {
                        min_y: 2016,
                        height: i32::MAX - 15,
                        logical_height: 0,
                        ..Default::default()
                    },
                );
                r.register_dimension(
                    "custom",
                    DimensionSettings {
                        generator: "test:void".into(),
                        ..Default::default()
                    },
                );
            }
        }
        let errors = install_parts(&[ModEntry::new("test", Box::new(Invalid))]).unwrap_err();
        assert_eq!(errors.len(), 7, "{errors:?}");
        assert!(errors[0].contains("test registered dimension test:pocket twice"));
        assert!(errors[1].contains("namespace"));
        assert!(errors[2].contains("no name"));
        assert!(errors[3].contains("test:uneven"));
        assert!(errors[4].contains("test:low_ceiling"));
        assert!(errors[5].contains("test:too_tall"));
        assert!(errors[6].contains("test:custom with the unknown generator \"test:void\""));
    }

    /// The vanilla levels are in the `minecraft` namespace, so only a mod with
    /// that id gets as far as naming one.
    #[test]
    fn a_vanilla_level_refuses_registration() {
        struct Vanilla;
        #[mod_api::__subscriptions]
        impl Hooks for Vanilla {
            fn register(&self, r: &mut dyn Registrar, _: &mod_api::RegistrationContext) {
                r.register_dimension("the_end", mod_api::DimensionSettings::default());
            }
        }
        let errors = install_parts(&[ModEntry::new("minecraft", Box::new(Vanilla))]).unwrap_err();
        assert_eq!(errors.len(), 1);
        assert!(errors[0].contains("minecraft:the_end, which is a vanilla level"));
    }

    /// A registered dimension reaches the engine as the level stem and
    /// dimension type a data pack would give.
    #[test]
    fn a_registered_dimension_reaches_the_engine_as_pack_entries() {
        use horizon_world::worldgen::overrides::{DIMENSION_TYPES, DIMENSIONS, WorldgenOverrides};
        struct Pocket;
        #[mod_api::__subscriptions]
        impl Hooks for Pocket {
            fn register(&self, r: &mut dyn Registrar, _: &mod_api::RegistrationContext) {
                r.register_dimension(
                    "test:pocket",
                    mod_api::DimensionSettings {
                        min_y: -128,
                        height: 448,
                        logical_height: 320,
                        has_skylight: false,
                        has_ceiling: true,
                        noise_settings: "minecraft:caves".into(),
                        biome: "minecraft:lush_caves".into(),
                        ..Default::default()
                    },
                );
            }
        }
        install_parts(&[ModEntry::new("test", Box::new(Pocket))]).unwrap();
        let dimensions = mod_api::__private::installed_dimensions();
        assert_eq!(dimensions.len(), 1);
        let mut overrides = WorldgenOverrides::default();
        overrides.add_mod_dimension(&dimensions[0]);
        let height = overrides.level_height("test:pocket").unwrap();
        assert_eq!(
            (
                height.min_y,
                height.height,
                height.logical_height,
                height.has_skylight,
                height.has_ceiling
            ),
            (-128, 448, 320, false, true)
        );
        assert_eq!(overrides.entries(DIMENSION_TYPES).count(), 1);
        let (id, stem) = overrides.entries(DIMENSIONS).next().unwrap();
        assert_eq!(id, "test:pocket");
        let stem: serde_json::Value = serde_json::from_str(stem).unwrap();
        assert_eq!(
            stem,
            serde_json::json!({
                "type": "test:pocket",
                "generator": {
                    "type": "minecraft:noise",
                    "settings": "minecraft:caves",
                    "biome_source": {"type": "minecraft:fixed", "biome": "minecraft:lush_caves"},
                },
            })
        );
    }
}
