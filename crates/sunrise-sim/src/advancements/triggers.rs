//! Identities whose trigger instances and matchers belong to the engine.

/// A registered vanilla `CriteriaTriggers` key, independent of which advancements are loaded.
/// The native matcher takes only custom trigger instances, not vanilla event payloads.
pub fn is_builtin_trigger(id: &str) -> bool {
    let Some(path) = id.strip_prefix("minecraft:") else {
        return false;
    };
    matches!(
        path,
        "allay_drop_item_on_block"
            | "any_block_use"
            | "avoid_vibration"
            | "bee_nest_destroyed"
            | "bred_animals"
            | "brewed_potion"
            | "changed_dimension"
            | "channeled_lightning"
            | "construct_beacon"
            | "consume_item"
            | "crafter_recipe_crafted"
            | "cured_zombie_villager"
            | "default_block_use"
            | "effects_changed"
            | "enchanted_item"
            | "enter_block"
            | "entity_hurt_player"
            | "entity_killed_player"
            | "fall_after_explosion"
            | "fall_from_height"
            | "filled_bucket"
            | "fishing_rod_hooked"
            | "hero_of_the_village"
            | "impossible"
            | "inventory_changed"
            | "item_durability_changed"
            | "item_used_on_block"
            | "killed_by_arrow"
            | "kill_mob_near_sculk_catalyst"
            | "levitation"
            | "lightning_strike"
            | "location"
            | "nether_travel"
            | "placed_block"
            | "player_generates_container_loot"
            | "player_hurt_entity"
            | "player_interacted_with_entity"
            | "player_killed_entity"
            | "player_sheared_equipment"
            | "recipe_crafted"
            | "recipe_unlocked"
            | "ride_entity_in_lava"
            | "shot_crossbow"
            | "slept_in_bed"
            | "slide_down_block"
            | "spear_mobs"
            | "started_riding"
            | "summoned_entity"
            | "tame_animal"
            | "target_hit"
            | "thrown_item_picked_up_by_entity"
            | "thrown_item_picked_up_by_player"
            | "tick"
            | "used_ender_eye"
            | "used_totem"
            | "using_item"
            | "villager_trade"
            | "voluntary_exile"
    )
}
