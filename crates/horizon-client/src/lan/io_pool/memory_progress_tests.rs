//! Direct readiness regressions: no pool thread, sweep, tick or timer can help.
use super::*;
use horizon_protocol::connection::Connection;
use std::sync::mpsc;

const PIPE_CAPACITY: usize = 64 * 1024;
struct Quiet;
impl Session for Quiet {
    fn packet(&mut self, _: i32, _: Vec<u8>) -> Verdict {
        panic!("no peer input expected")
    }
    fn tick(&mut self, _: Instant) -> Option<Vec<u8>> {
        panic!("test must not sweep")
    }
    fn left(&mut self, reason: String) {
        panic!("unexpected disconnect: {reason}")
    }
    fn closed(&mut self) {}
}
fn worker(poll: &Poll) -> Arc<Worker> {
    Arc::new(Worker {
        waker: Waker::new(poll.registry(), WAKER).unwrap(),
        inbox: Mutex::new(Inbox::default()),
        load: AtomicUsize::new(1),
    })
}
fn outbox(worker: Arc<Worker>) -> Arc<Outbox> {
    // Rebind the fresh, unadopted outbox to our private worker. The global
    // pool never owns or services this connection, even if it was initialized.
    let mut outbox = Outbox::new(Arc::default(), false).unwrap();
    Arc::get_mut(&mut outbox).unwrap().worker = worker;
    outbox
}
fn register(server: Connection, poll: &Poll, worker: &Arc<Worker>, outbox: Arc<Outbox>) -> Conn {
    let (socket, reader, writer) = server.detach();
    Conn::register(
        Adopted {
            socket,
            reader,
            writer,
            outbox,
            session: Box::new(Quiet),
            timeout: Duration::from_secs(30),
        },
        poll.registry(),
        worker,
        0,
        Instant::now(),
    )
    .unwrap_or_else(|()| panic!("registration failed"))
}
fn queue(outbox: &Outbox, body: Vec<u8>) {
    outbox.pending.fetch_add(charge(&body), Ordering::Relaxed);
    // Keep the connection in Coming: no unrelated serve notification is posted.
    outbox.push(vec![body], None);
}
fn drain(pipe: &mut Pipe) -> Vec<u8> {
    let mut bytes = Vec::new();
    loop {
        let mut buf = [0; 8192];
        match pipe.read(&mut buf) {
            Ok(0) => panic!("unexpected close"),
            Ok(n) => bytes.extend_from_slice(&buf[..n]),
            Err(e) if e.kind() == ErrorKind::WouldBlock => return bytes,
            Err(e) => panic!("read failed: {e}"),
        }
    }
}
#[test]
fn memory_server_resumes_only_from_capacity_readiness() {
    let poll = Poll::new().unwrap();
    let worker = worker(&poll);
    let outbox = outbox(worker.clone());
    let (server, mut peer) = Pipe::pair();
    peer.set_nonblocking(true);
    let mut conn = register(Connection::local(server), &poll, &worker, outbox.clone());
    // Discard registration's initially-writable callback before filling the pipe.
    worker.inbox.lock().unwrap().read.clear();
    let body = vec![0x37; 2 * PIPE_CAPACITY];
    queue(&outbox, body.clone());
    conn.serve(Instant::now()); // The sole initial publication drive.
    assert_eq!(conn.written, PIPE_CAPACITY);
    assert!(conn.out.len() > conn.written);
    assert!(worker.inbox.lock().unwrap().read.is_empty());
    let mut received = drain(&mut peer);
    assert_eq!(received.len(), PIPE_CAPACITY);
    let ready = std::mem::take(&mut worker.inbox.lock().unwrap().read);
    assert!(
        !ready.is_empty(),
        "draining must trigger the real Pipe callback"
    );
    assert!(worker.inbox.lock().unwrap().serve.is_empty());
    let before = conn.out.len() - conn.written;
    for slot in ready {
        assert_eq!(slot, 0);
        conn.memory_ready(Instant::now()); // Exact handler used by inbox.read.
    }
    assert!(
        conn.out.len() - conn.written < before,
        "capacity-ready handler did not resume pending server output"
    );
    received.extend(drain(&mut peer));
    // Finish exclusively through callbacks generated by each drain.
    while !conn.out.is_empty() {
        let ready = std::mem::take(&mut worker.inbox.lock().unwrap().read);
        assert!(!ready.is_empty());
        for _ in ready {
            conn.memory_ready(Instant::now());
        }
        received.extend(drain(&mut peer));
    }
    let mut expected = (body.len() as u64).to_le_bytes().to_vec();
    expected.extend(body);
    assert_eq!(received, expected);
}
#[test]
fn blocking_client_writer_resumes_when_server_drains() {
    let (mut client, mut server) = Pipe::pair();
    client.set_nonblocking(true);
    client.write_all(&vec![0x41; PIPE_CAPACITY]).unwrap();
    assert_eq!(
        client.write(&[0]).unwrap_err().kind(),
        ErrorKind::WouldBlock
    );
    client.set_nonblocking(false);
    server.set_nonblocking(true);
    // split retains the live memory stream; detach would disable direct writes.
    let (_client_reader, mut writer) = Connection::local(client).split();
    let (started_tx, started_rx) = mpsc::channel();
    let (done_tx, done_rx) = mpsc::channel();
    let thread = std::thread::spawn(move || {
        started_tx.send(()).unwrap();
        done_tx.send(writer.send(&[0x23, 0x45])).unwrap();
    });
    started_rx.recv_timeout(Duration::from_secs(5)).unwrap();
    assert!(matches!(done_rx.try_recv(), Err(mpsc::TryRecvError::Empty)));
    // Release capacity without registering or driving any readiness callback.
    let mut full = vec![0; PIPE_CAPACITY];
    server.read_exact(&mut full).unwrap();
    assert_eq!(full, vec![0x41; PIPE_CAPACITY]);
    done_rx
        .recv_timeout(Duration::from_secs(5))
        .unwrap()
        .unwrap();
    thread.join().unwrap();
    let mut expected = 2u64.to_le_bytes().to_vec();
    expected.extend([0x23, 0x45]);
    // The retained client reader keeps the endpoint alive through verification.
    let mut actual = vec![0; expected.len()];
    server.read_exact(&mut actual).unwrap();
    assert_eq!(actual, expected);
}
#[test]
#[ignore = "daily"]
fn tcp_server_resumes_only_from_writable_readiness() {
    let mut poll = Poll::new().unwrap();
    let worker = worker(&poll);
    let outbox = outbox(worker.clone());
    let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
    let mut peer = std::net::TcpStream::connect(listener.local_addr().unwrap()).unwrap();
    peer.set_read_timeout(Some(Duration::from_secs(5))).unwrap();
    let mut socket = listener.accept().unwrap().0;
    socket.set_nonblocking(true).unwrap();
    let fill = [0x51; 65536];
    let fill_until = Instant::now() + Duration::from_secs(5);
    let mut filled = 0;
    let mut offset = 0;
    loop {
        assert!(Instant::now() < fill_until, "socket prefill timed out");
        match socket.write(&fill[offset..]) {
            Ok(n) => {
                assert!(n > 0, "socket closed during prefill");
                filled += n;
                assert!(filled < MAX_PENDING, "socket did not apply backpressure");
                offset = (offset + n) % fill.len();
            }
            Err(e) if e.kind() == ErrorKind::WouldBlock => break,
            Err(e) if e.kind() == ErrorKind::Interrupted => {}
            Err(e) => panic!("socket prefill: {e}"),
        }
    }
    socket.set_nonblocking(false).unwrap();
    let server = Connection::from_stream(socket).unwrap();
    let mut conn = register(server, &poll, &worker, outbox.clone());
    let body = vec![0x23; 1 << 20];
    queue(&outbox, body.clone());
    conn.serve(Instant::now()); // Sole initial publication drive, reader held.
    assert!(
        conn.stalled.is_some(),
        "prefilled socket must reach WouldBlock"
    );
    let remaining = conn.out.len() - conn.written;
    assert!(remaining > 0);
    assert!(worker.inbox.lock().unwrap().serve.is_empty());
    // Consume any registration-era notification before releasing the reader.
    let mut events = Events::with_capacity(8);
    poll.poll(&mut events, Some(Duration::ZERO)).unwrap();
    // Independent wire expectation: VarInt(1 MiB), then the packet body.
    let mut expected = vec![0x51; filled];
    expected.extend([0x80, 0x80, 0x40]);
    expected.extend(body);
    let len = expected.len();
    let (tx, rx) = mpsc::channel();
    let reader = std::thread::spawn(move || {
        let mut bytes = vec![0; len];
        let result = peer.read_exact(&mut bytes).map(|()| bytes);
        let _ = tx.send(result);
    });
    let until = Instant::now() + Duration::from_secs(5);
    let mut writable_events = 0;
    while conn.out.len() > conn.written {
        let left = until.saturating_duration_since(Instant::now());
        assert!(!left.is_zero(), "TCP writable resumption timed out");
        poll.poll(&mut events, Some(left)).unwrap();
        for event in &events {
            if event.token() != Token(0) {
                continue;
            }
            // The same writable branch used in production run. No sweep,
            // tick, new publication or unrelated serve drives this connection.
            if event.is_writable() || event.is_write_closed() || event.is_error() {
                assert!(
                    event.is_writable(),
                    "expected capacity readiness, not close/error"
                );
                writable_events += 1;
                conn.serve(Instant::now());
            }
        }
    }
    assert!(writable_events > 0);
    assert!(conn.out.len() - conn.written < remaining);
    assert_eq!(
        rx.recv_timeout(Duration::from_secs(5)).unwrap().unwrap(),
        expected
    );
    reader.join().unwrap();
}
